/// Rebuilds the browser animation engine and embeds it into the web app.
///
/// `anim-wasm` (repo root) compiles the *real* firmware `animations` crate
/// to `wasm32-unknown-unknown`; this script runs that build, shrinks the
/// artifact with `wasm-opt -Oz` when it's on PATH, and writes it base64 into
/// `src/lib/wasm_gen.ts`. Base64-inline (not a fetchable asset) because the
/// board serves the whole SPA as one gzipped HTML file — there is no second
/// route for a `.wasm` — and the sim embeds the same bundle.
///
/// Run from `web/`: `deno task wasm` (or `just wasm`). `compile.sh` runs it
/// before the vite build. Keep rustup's cargo on PATH (AGENTS.md): the
/// Homebrew toolchain has no wasm target.
const TARGET = "wasm32-unknown-unknown";
const PROFILE = "release-wasm";

const wasmPath = `../target/${TARGET}/${PROFILE}/anim_wasm.wasm`;

const build = await new Deno.Command("cargo", {
  args: ["build", "-p", "anim-wasm", "--target", TARGET, "--profile", PROFILE],
  cwd: "..",
  stdout: "inherit",
  stderr: "inherit",
}).output();

if (!build.success) {
  console.error(
    '`cargo build -p anim-wasm` failed — rustup\'s cargo on PATH? (AGENTS.md: export PATH="$HOME/.cargo/bin:$PATH")',
  );
  Deno.exit(build.code ?? 1);
}

let bytes = await Deno.readFile(wasmPath);
const raw = bytes.length;

try {
  const opt = await new Deno.Command("wasm-opt", {
    // -all: the artifact uses saturating float casts + bulk memory — every
    // engine that runs WebAssembly 2.0-era browsers accepts both.
    args: ["-Oz", "-all", "--strip-debug", "--strip-producers", wasmPath, "--output", `${wasmPath}.opt`],
    stdout: "inherit",
    stderr: "inherit",
  }).output();

  if (opt.success) {
    bytes = await Deno.readFile(`${wasmPath}.opt`);
    await Deno.remove(`${wasmPath}.opt`);
  }
} catch (err) {
  console.warn("wasm-opt not found — embedding the unoptimised artifact", err);
}

const b64 = base64Of(bytes);
const generated = `/// <generated by web/embed_wasm.ts — do not edit; regenerate with \`deno task wasm\`>
/// The \`anim-wasm\` crate (the firmware animation renderers) compiled for
/// wasm32-unknown-unknown, base64-encoded. \`web/src/lib/preview.ts\`
/// instantiates this so previews run the same Rust the panel does.
/// Size: ${bytes.length} B wasm (${raw} B before wasm-opt), ${b64.length} B base64.
export const ANIM_WASM_BASE64 =
  "${b64}";
`;

await Deno.writeTextFile("src/lib/wasm_gen.ts", generated);

console.log(`embedded anim_wasm.wasm: wasm ${raw} B → ${bytes.length} B, base64 ${b64.length} B`);

function base64Of(data: Uint8Array): string {
  let binary = "";

  for (let i = 0; i < data.length; i += 0x8000) {
    binary += String.fromCharCode(...data.subarray(i, i + 0x8000));
  }

  return btoa(binary);
}
